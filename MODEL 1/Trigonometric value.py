import math

Angle_degree = 90
Angle_radian = math.radians(Angle_degree)

sin_value = math.sin(Angle_radian)
cos_value = math.cos(Angle_radian)
tan_value = math.tan(Angle_radian)

print("The Angle is",Angle_degree)
print("sin value =",sin_value)
print("cos value =",cos_value)
print("tan value =",tan_value)